const worksheetPreview = document.getElementById("worksheetPreview");

const gradeSelect = document.getElementById("grade");
const operationSelect = document.getElementById("operation");
const difficultySelect = document.getElementById("difficulty");
const questionCountSelect = document.getElementById("questionCount");
const studentNameInput = document.getElementById("studentName");

let currentQuestions = [];

function random(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function getDifficultyRange() {
  const difficulty = difficultySelect.value;

  switch (difficulty) {
    case "easy":
      return [1, 10];

    case "medium":
      return [10, 50];

    case "hard":
      return [50, 100];

    default:
      return [1, 20];
  }
}

function generateQuestion() {
  const operation = operationSelect.value;

  const [min, max] = getDifficultyRange();

  let a = random(min, max);
  let b = random(min, max);

  let question = "";
  let answer = 0;

  switch (operation) {
    case "addition":
      question = `${a} + ${b} =`;
      answer = a + b;
      break;

    case "subtraction":
      if (b > a) {
        [a, b] = [b, a];
      }

      question = `${a} - ${b} =`;
      answer = a - b;
      break;

    case "multiplication":
      a = random(1, 12);
      b = random(1, 12);

      question = `${a} × ${b} =`;
      answer = a * b;
      break;

    case "division":
      answer = random(1, 12);
      b = random(1, 12);
      a = answer * b;

      question = `${a} ÷ ${b} =`;
      break;
  }

  return {
    question,
    answer,
  };
}

function createQuestions() {
  const total = parseInt(questionCountSelect.value);

  currentQuestions = [];

  for (let i = 0; i < total; i++) {
    currentQuestions.push(generateQuestion());
  }
}

function renderWorksheet() {
  if (!currentQuestions.length) {
    worksheetPreview.innerHTML = `
      <div class="a4-page">
        <div class="questions empty">
          No worksheet generated yet.
        </div>
      </div>
    `;
    return;
  }

  const studentName = studentNameInput.value || "________________";
  const grade = gradeSelect.options[gradeSelect.selectedIndex].text;
  const operation =
    operationSelect.options[operationSelect.selectedIndex].text;

  const questionsHTML = currentQuestions
    .map((q, index) => {
      return `
        <div class="question">
          ${index + 1}. ${q.question}
          <span class="answer-line"></span>
        </div>
      `;
    })
    .join("");

  const answersHTML = currentQuestions
    .map((q, index) => {
      return `
        <div>
          ${index + 1}) ${q.answer}
        </div>
      `;
    })
    .join("");

  worksheetPreview.innerHTML = `
    <div class="a4-page">

      <div class="a4-header">

        <div class="logo-mark">
          AI
        </div>

        <div class="a4-title-block">
          <h2>Math Worksheet</h2>
          <p>Professional printable worksheet generated by TeachSheet AI</p>
        </div>

        <div class="a4-brand">
          TeachSheet AI
        </div>

      </div>

      <div class="a4-info-grid">

        <div>
          <strong>Student:</strong><br>
          ${studentName}
        </div>

        <div>
          <strong>Grade:</strong><br>
          ${grade}
        </div>

        <div>
          <strong>Operation:</strong><br>
          ${operation}
        </div>

      </div>

      <div class="a4-divider"></div>

      <div class="questions">
        ${questionsHTML}
      </div>

      <div class="answer-key">

        <h3>Answer Key</h3>

        <div class="answer-grid">
          ${answersHTML}
        </div>

      </div>

      <div class="a4-footer">
        Generated by TeachSheet AI — Printable Classroom Worksheets
      </div>

    </div>
  `;
}

function generateWorksheet() {
  createQuestions();

  renderWorksheet();
}

function clearWorksheet() {
  currentQuestions = [];

  worksheetPreview.innerHTML = `
    <div class="a4-page">
      <div class="questions empty">
        No worksheet generated yet.
      </div>
    </div>
  `;
}

async function downloadPDF() {
  if (!currentQuestions.length) {
    alert("Generate worksheet first.");
    return;
  }

  const { jsPDF } = window.jspdf;

  const pdf = new jsPDF("p", "mm", "a4");

  pdf.setDrawColor(13, 140, 255);
  pdf.setLineWidth(1.2);

  pdf.roundedRect(10, 10, 190, 277, 4, 4);

  pdf.setFillColor(13, 140, 255);
  pdf.roundedRect(18, 18, 174, 24, 4, 4, "F");

  pdf.setTextColor(255, 255, 255);

  pdf.setFontSize(22);
  pdf.setFont("helvetica", "bold");

  pdf.text("Math Worksheet", 24, 33);

  pdf.setFontSize(10);

  pdf.text("Generated by TeachSheet AI", 145, 33);

  pdf.setTextColor(0, 0, 0);

  pdf.setFontSize(12);

  const studentName =
    studentNameInput.value || "________________";

  const grade =
    gradeSelect.options[gradeSelect.selectedIndex].text;

  const operation =
    operationSelect.options[operationSelect.selectedIndex].text;

  pdf.text(`Student: ${studentName}`, 20, 55);
  pdf.text(`Grade: ${grade}`, 90, 55);
  pdf.text(`Operation: ${operation}`, 150, 55);

  pdf.setDrawColor(220, 220, 220);

  pdf.line(18, 62, 192, 62);

  let y = 75;

  currentQuestions.forEach((q, index) => {
    if (y > 250) {
      addPdfFooter(pdf);

      pdf.addPage();

      pdf.setDrawColor(13, 140, 255);
      pdf.setLineWidth(1.2);

      pdf.roundedRect(10, 10, 190, 277, 4, 4);

      y = 25;
    }

    const leftColumn = index % 2 === 0;

    const x = leftColumn ? 20 : 110;

    pdf.setDrawColor(220, 220, 220);

    pdf.roundedRect(x - 4, y - 7, 74, 14, 3, 3);

    pdf.setFontSize(14);
    pdf.setFont("helvetica", "bold");

    pdf.text(
      `${index + 1}. ${q.question} ______`,
      x,
      y
    );

    if (!leftColumn) {
      y += 18;
    }
  });

  y += 14;

  pdf.setFillColor(240, 253, 244);

  pdf.roundedRect(18, y, 174, 42, 4, 4, "F");

  pdf.setFontSize(16);

  pdf.text("Answer Key", 24, y + 10);

  pdf.setFontSize(11);

  let answerX = 24;
  let answerY = y + 22;

  currentQuestions.forEach((q, index) => {
    pdf.text(
      `${index + 1}) ${q.answer}`,
      answerX,
      answerY
    );

    answerX += 32;

    if ((index + 1) % 5 === 0) {
      answerX = 24;
      answerY += 8;
    }
  });

  addPdfFooter(pdf);

  pdf.save("teachsheet-ai-worksheet.pdf");
}

function addPdfFooter(pdf) {
  pdf.setFontSize(9);

  pdf.setTextColor(120, 120, 120);

  pdf.text(
    "Generated by TeachSheet AI",
    105,
    285,
    {
      align: "center",
    }
  );
}

window.generateWorksheet = generateWorksheet;
window.downloadPDF = downloadPDF;
window.clearWorksheet = clearWorksheet;

clearWorksheet();
